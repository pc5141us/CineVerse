#!/bin/bash
# CineVerse - سكريبت الرفع والنشر المباشر على Vercel بنقرة واحدة
export PATH="$PATH:/usr/local/bin:/opt/homebrew/bin"
cd "$(dirname "$0")"

echo "======================================================"
echo "🚀 جاري بدء عملية الرفع إلى منصة Vercel..."
echo "======================================================"

# التحقق من تشغيل npx vercel
if command -v npx > /dev/null; then
  echo "⚡ جاري تجهيز وتشغيل أداة Vercel..."
  echo "إذا كانت هذه أول مرة، سيفتح المتصفح لتسجيل الدخول."
  echo "اضغط Enter للموافقة على الإعدادات الافتراضية."
  echo "------------------------------------------------------"
  npx vercel
  echo "------------------------------------------------------"
  echo "للنشر على النطاق النهائي للإنتاج (Production)، نفذ:"
  echo "npx vercel --prod"
else
  echo "❌ Node.js / npx غير مثبت في المسار الافتراضي."
fi
